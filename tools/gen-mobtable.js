// Regenerates plugin/HuntHop/MobTable.cs and ZoneTable.cs (same folder) from the faloop.app JS bundle.
//
// Usage:
//   1. Download the bundle: open https://faloop.app, find the main.<hash>.js script URL
//      in the page source, save it to a folder of its own.
//   2. node tools/gen-mobtable.js <path-to-main.js> plugin/HuntHop/MobTable.cs
//
// It reads the bundle as text only (never executes it).
const fs = require('fs');
const path = require('path');

const [bundlePath, outPath] = process.argv.slice(2);
if (!bundlePath || !outPath) {
  console.error('usage: node gen-mobtable.js <main.js> <MobTable.cs>');
  process.exit(1);
}

const src = fs.readFileSync(bundlePath, 'utf8');
// Mob entries look like: sansheya:{id:"sansheya",name:{en:"Sansheya",...},rank:"S",expansionId:"dawntrail",zoneIds:["shaaloani"],...
const re = /([a-z0-9_]+):\{id:"\1",name:\{en:"([^"]+)"[^}]*\},rank:"(SS|S|A|B|F)",expansionId:"([a-z_]+)",zoneIds:\[([^\]]*)\]/g;
const mobs = [];
for (let m; (m = re.exec(src)); ) {
  if (!['SS', 'S', 'F'].includes(m[3])) continue;
  mobs.push({ id: m[1], name: m[2], rank: m[3], exp: m[4], zones: m[5].split('"').join('').split(',') });
}
if (mobs.length < 30) {
  console.error(`only ${mobs.length} mobs matched; the bundle format probably changed`);
  process.exit(2);
}

const esc = s => s.split('\\').join('\\\\').split('"').join('\\"');
const lines = mobs.map(m =>
  `        ["${m.id}"] = new("${m.id}", "${esc(m.name)}", "${m.rank}", "${m.exp}", ["${m.zones.join('", "')}"]),`);
const out = `// <auto-generated>
// Generated from the faloop.app bundle (${path.basename(bundlePath)}) on ${new Date().toLocaleDateString('sv-SE')}
// by tools/gen-mobtable.js. Ranks: SS, S, F (hunt FATE). Regenerate after a new
// expansion or when Faloop adds mobs.
// </auto-generated>
namespace HuntHop;

internal sealed record MobInfo(string Id, string Name, string Rank, string Expansion, string[] Zones);

internal static class MobTable
{
    public static readonly IReadOnlyDictionary<string, MobInfo> All = new Dictionary<string, MobInfo>(StringComparer.OrdinalIgnoreCase)
    {
${lines.join('\n')}
    };

    public static bool TryGet(string id, out MobInfo info) => All.TryGetValue(id, out info!);
}
`;
fs.writeFileSync(outPath, out);
console.log(`wrote ${mobs.length} mobs to ${outPath}`);

// ── ZoneTable.cs: aetherytes + spawn points of the zones those mobs live in ──
// Zone entries: shaaloani:{id:"shaaloani",name:{en:"Shaaloani",...},expansionId:"…",territoryId:"…",
//   map:{pixelSize:…,offset:{x:…,y:…},sizeFactor:100},pois:[{id:1216,name:{en:"Mehwahhetsoan",…},
//   type:"aetheryte",location:"1329,465"},{id:6,type:"mob",location:"777,345",journeyPoiId:1},…]}
// POI ids are unique across zones; locations are map-texture pixels (0–2048).
const usedZones = new Set(mobs.flatMap(m => m.zones));
const head = /([a-z0-9_]+):\{id:"\1",name:\{en:"([^"]+)"[^}]*\},expansionId:"[a-z_]+",territoryId:"[a-z0-9_]+",map:\{pixelSize:\d+,offset:\{x:-?\d+,y:-?\d+\},sizeFactor:(\d+)\},pois:\[/g;
const zones = [];
for (let m; (m = head.exec(src)); ) {
  let i = head.lastIndex, depth = 1;
  while (depth > 0 && i < src.length) { const c = src[i++]; if (c === '[') depth++; else if (c === ']') depth--; }
  if (!usedZones.has(m[1])) continue;
  const body = src.slice(head.lastIndex, i - 1);
  const aetherytes = [], spawns = [];
  const poi = /\{id:(\d+),(?:name:\{en:"([^"]*)"[^}]*\},)?type:"(\w+)",location:"(\d+),(\d+)"/g;
  for (let p; (p = poi.exec(body)); ) {
    if (p[3] === 'aetheryte') aetherytes.push({ id: +p[1], name: p[2] || '', x: +p[4], y: +p[5] });
    else if (p[3] === 'mob') spawns.push([+p[1], +p[4], +p[5]]);
  }
  zones.push({ id: m[1], name: m[2], sizeFactor: +m[3], aetherytes, spawns });
}
const missing = [...usedZones].filter(z => !zones.find(x => x.id === z));
if (zones.length < 20 || missing.length > usedZones.size / 4) {
  console.error(`zone parse looks wrong: ${zones.length} zones, missing ${missing.join(', ')}`);
  process.exit(3);
}
const zoneLines = zones.map(z =>
  `        new("${z.id}", "${esc(z.name)}", ${z.sizeFactor},\n` +
  `            [${z.aetherytes.map(a => `new(${a.id}, "${esc(a.name)}", ${a.x}, ${a.y})`).join(', ')}],\n` +
  `            [${z.spawns.map(s => s.join(', ')).join(', ')}]),`);
const zoneOut = `// <auto-generated>
// Generated from the faloop.app bundle (${path.basename(bundlePath)}) on ${new Date().toLocaleDateString('sv-SE')}
// by tools/gen-mobtable.js, together with MobTable.cs. Zones that SS / S / hunt-FATE mobs live in,
// with their aetherytes and Faloop's spawn points (POI id, x, y in map-texture pixels, 0-2048).
// </auto-generated>
namespace HuntHop;

internal sealed record ZoneAetheryte(int PoiId, string Name, int X, int Y);

/// <summary>SpawnPoints is a flat list of (poiId, x, y) triples.</summary>
internal sealed record ZoneInfo(string Id, string Name, int SizeFactor, ZoneAetheryte[] Aetherytes, int[] SpawnPoints);

internal static partial class ZoneTable
{
    public static readonly ZoneInfo[] All =
    [
${zoneLines.join('\n')}
    ];
}
`;
const zonePath = path.join(path.dirname(outPath), 'ZoneTable.cs');
fs.writeFileSync(zonePath, zoneOut);
const sp = zones.reduce((a, z) => a + z.spawns.length, 0), ae = zones.reduce((a, z) => a + z.aetherytes.length, 0);
console.log(`wrote ${zones.length} zones (${ae} aetherytes, ${sp} spawn points) to ${zonePath}` + (missing.length ? `; no zone data for: ${missing.join(', ')}` : ''));
